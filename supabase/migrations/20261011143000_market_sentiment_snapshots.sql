-- Optional historical sentiment storage. The backend keeps using its in-memory
-- repository unless a Supabase repository is explicitly configured.
create table if not exists public.market_sentiment_snapshots (
  id bigint generated by default as identity primary key,
  timestamp timestamptz not null unique,
  score numeric,
  label text not null,
  confidence numeric not null,
  data_quality text not null,
  regime text not null,
  nifty_momentum numeric,
  market_breadth numeric,
  sector_breadth numeric,
  india_vix numeric,
  news_sentiment numeric,
  volume_momentum numeric,
  bank_nifty numeric,
  alignment_score numeric,
  forward_return_15m numeric,
  forward_return_30m numeric,
  forward_return_1h numeric,
  forward_return_eod numeric,
  forward_return_1d numeric,
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists market_sentiment_snapshots_timestamp_idx
  on public.market_sentiment_snapshots (timestamp);

alter table public.market_sentiment_snapshots enable row level security;

drop policy if exists "authenticated users can read market sentiment snapshots"
  on public.market_sentiment_snapshots;
create policy "authenticated users can read market sentiment snapshots"
  on public.market_sentiment_snapshots for select
  to authenticated using (true);
