// Builds src/data/instrument-master.ts from official NSE files kept in audit/implementation/reference/nse.
// Usage: node scripts/build-instrument-master.mjs <ind_nifty50list.csv> <EQUITY_L.csv> <retrieved YYYY-MM-DD>
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const [indexFile, equityFile, retrieved] = process.argv.slice(2);
if (!indexFile || !equityFile || !/^\d{4}-\d{2}-\d{2}$/.test(retrieved ?? ""))
  throw new Error("Usage: build-instrument-master.mjs <index.csv> <equity.csv> <YYYY-MM-DD>");
const sha = (file) => createHash("sha256").update(readFileSync(file)).digest("hex");
// Both NSE files are simple comma-separated values without quoted commas; verify that.
const rows = (file) =>
  readFileSync(file, "utf8")
    .trim()
    .split(/\r?\n/)
    .map((line) => line.split(",").map((cell) => cell.trim()));
const [indexHeader, ...index] = rows(indexFile);
const [equityHeader, ...equities] = rows(equityFile);
if (indexHeader.join("|") !== "Company Name|Industry|Symbol|Series|ISIN Code")
  throw new Error(`Unexpected index header ${indexHeader}`);
if (!equityHeader[0]?.startsWith("SYMBOL") || equityHeader.length !== 8)
  throw new Error(`Unexpected equity header ${equityHeader}`);
if (index.some((row) => row.length !== 5) || equities.some((row) => row.length !== 8))
  throw new Error("A row contains an embedded comma; use a CSV parser before regenerating");
const bySymbol = new Map(equities.map((row) => [row[0], row]));
const months = {
  JAN: "01",
  FEB: "02",
  MAR: "03",
  APR: "04",
  MAY: "05",
  JUN: "06",
  JUL: "07",
  AUG: "08",
  SEP: "09",
  OCT: "10",
  NOV: "11",
  DEC: "12",
};
const instruments = index.map(([company, industry, symbol, series, isin]) => {
  const equity = bySymbol.get(symbol);
  if (!equity) throw new Error(`${symbol} missing from equity master`);
  if (equity[6] !== isin) throw new Error(`${symbol} ISIN mismatch ${equity[6]} vs ${isin}`);
  const [day, month, year] = equity[3].split("-");
  return {
    symbol,
    company: company.replace(/ Ltd\.$/, ""),
    industry,
    series,
    isin,
    listing_date: `${year}-${months[month.toUpperCase()]}-${day}`,
    market_lot: Number(equity[5]),
    face_value: Number(equity[7]),
  };
});
if (instruments.length !== 50)
  throw new Error(`Expected 50 constituents, got ${instruments.length}`);
const source = {
  index_file: "ind_nifty50list.csv",
  index_sha256: sha(indexFile),
  equity_file: "EQUITY_L.csv",
  equity_sha256: sha(equityFile),
  retrieved,
  urls: [
    "https://nsearchives.nseindia.com/content/indices/ind_nifty50list.csv",
    "https://nsearchives.nseindia.com/content/equities/EQUITY_L.csv",
  ],
};
writeFileSync(
  "src/data/instrument-master.ts",
  `// Generated by scripts/build-instrument-master.mjs from official NSE files. Do not edit by hand.
// Membership is as published on the retrieval date; it is not a historical (point-in-time) record.
export type MasterInstrument = {
  symbol: string;
  company: string;
  industry: string;
  series: string;
  isin: string;
  listing_date: string;
  market_lot: number;
  face_value: number;
};

export const INSTRUMENT_MASTER_SOURCE = ${JSON.stringify(source, null, 2)} as const;

export const NIFTY50_MASTER: MasterInstrument[] = ${JSON.stringify(instruments, null, 2)};
`,
);
console.log(`Wrote ${instruments.length} instruments (index ${source.index_sha256.slice(0, 12)}).`);
